export const DEFAULT_FONT_ID = FONT_PRESETS[0].id;

/** localStorage key for the visitor's choice. */
export const FONT_STORAGE_KEY = "museon-font";

const presetVars = (p: FontPreset) =>
  [
    `--font-heading:${p.heading.family}`,
    `--font-heading-weight:${p.heading.weight}`,
    `--font-heading-tracking:${p.heading.tracking}`,
    `--font-body:${p.body}`,
    `--font-ui:${p.ui}`,
    `--lh-display:${p.lineHeight.display}`,
    `--lh-title:${p.lineHeight.title}`,
    `--lh-text:${p.lineHeight.text}`,
  ].join(";");

/** CSS for every preset; the default also applies with no data-font set. */
export const buildFontThemeCss = () =>
  FONT_PRESETS.map((p, i) =>
    `${i === 0 ? ":root," : ""}html[data-font="${p.id}"]{${presetVars(p)}}`,
  ).join("");

/**
 * Inline <head> script: applies the saved preset before the first paint so
 * the page never flashes the default font.
 */
export const fontInitScript = `try{var f=localStorage.getItem(${JSON.stringify(
  FONT_STORAGE_KEY,
)});if(${JSON.stringify(FONT_PRESETS.map((p) => p.id))}.indexOf(f)>-1)document.documentElement.dataset.font=f}catch(e){}`;
