/*
 * Font presets: the single place to change the site's typography.
 *
 * Every component uses one of three font roles:
 *   heading → .font-heading / .font-boldCond  (titles)
 *   body    → .font-body                      (page default)
 *   ui      → .font-dmSans                    (paragraphs, buttons, nav)
 *
 * …and one of three line-height tokens (Tailwind utilities):
 *   leading-display → big section titles and the hero
 *   leading-title   → card titles, names, small headings
 *   leading-text    → paragraphs
 *
 * Each preset sets all of these. Fonts have different built-in spacing, so
 * tune `lineHeight` per preset rather than in components. The CSS for every
 * preset is generated by buildFontThemeCss() and switched with
 * <html data-font="<id>">. The first preset is the default.
 *
 * Google fonts are loaded in src/app/font/index.ts (--ff-* variables).
 * System fonts are written as normal font stacks.
 */

export type FontPreset = {
  id: string;
  label: string;
  description: string;
  /** Section heading in the switcher panel. */
  group: "Designer pairs" | "Popular fonts";
  heading: {
    family: string;
    /** Boldonse has one weight (400); most fonts look best at 700–800. */
    weight: number;
    /** letter-spacing, e.g. "0.02em" */
    tracking: string;
  };
  body: string;
  ui: string;
  lineHeight: {
    /** leading-display */
    display: number;
    /** leading-title */
    title: number;
    /** leading-text */
    text: number;
  };
};

